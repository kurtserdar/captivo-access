import { build } from "esbuild";
import { writeFileSync } from "node:fs";

const result = await build({
  entryPoints: ["src/recorder/record-init.ts"],
  bundle: true,
  format: "iife",
  minify: true,
  target: ["es2019"],
  write: false,
});
const js = result.outputFiles[0].text;
writeFileSync("src/recorder/rec.bundle.ts", `// GENERATED by scripts/build-recorder.mjs — do not edit.\nexport const RECORDER_JS = ${JSON.stringify(js)};\n`);
console.log("recorder bundle:", js.length, "bytes");
